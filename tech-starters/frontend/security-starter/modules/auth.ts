import { relative } from 'node:path';
import { addTemplate, defineNuxtModule, updateTemplates } from 'nuxt/kit';
import type { NuxtPage } from 'nuxt/schema';

export interface AuthOptions {
  /** The path under the API that answers the current user, or 401 to a visitor, such as `/api/user/me`. */
  currentUserPath?: string;
  /** The page a visitor goes to when a page asks to sign in. */
  signInPage?: string;
  /** The page a signed-in user goes to, by a role they hold, when a page needs a role they lack. */
  forbiddenRedirects?: Record<string, string>;
}

const CHECK = 'auth/pages-without-auth.ts';

/**
 * Configures the session of the app, and fails its type check on each page that does not declare who may open it:
 * Nuxt extracts the `auth` of `definePageMeta` at build time, when written as a literal.
 *
 * OWASP: ASVS 5.0 V8.2.1
 */
export default defineNuxtModule<AuthOptions>({
  meta: { name: 'auth', configKey: 'auth' },
  defaults: { signInPage: '/sign-in', forbiddenRedirects: {} },
  setup({ currentUserPath, signInPage, forbiddenRedirects }, nuxt) {
    // Typed by the values of each app once resolved: assigned whole, as the layer's defaults declare it
    Object.assign(nuxt.options.runtimeConfig.public, {
      auth: { currentUserPath: currentUserPath ?? '', signInPage, forbiddenRedirects },
    });
    nuxt.options.experimental.extraPageMetaExtractionKeys.push('auth');

    let pagesWithoutAuth: string[] = [];
    const check = addTemplate({ filename: CHECK, write: true, getContents: () => checkOf(pagesWithoutAuth) });

    nuxt.hook('pages:resolved', async (pages) => {
      if (!currentUserPath && pages.length > 0) {
        throw new Error('auth needs the currentUserPath of the API, such as /api/user/me');
      }

      pagesWithoutAuth = withoutAuth(pages).map((file) => relative(nuxt.options.rootDir, file));
      await updateTemplates({ filter: (template) => template.filename === CHECK });
    });

    nuxt.hook('prepare:types', ({ tsConfig }) => {
      tsConfig.include = [...tsConfig.include ?? [], relative(nuxt.options.buildDir, check.dst)];
    });
  },
});

// A child page inherits the meta of its parent; a route Nuxt adds without a file is not a page of the app
function withoutAuth(pages: NuxtPage[], inherited = false): string[] {
  return pages.flatMap((page) => {
    const declared = inherited || page.meta?.auth !== undefined;
    const own = declared || !page.file ? [] : [page.file];

    return [...own, ...withoutAuth(page.children ?? [], declared)];
  });
}

function checkOf(pages: string[]): string {
  const lines = pages.map((page) => `  DeclaresAuthInDefinePageMeta<${JSON.stringify(page)}>,`);

  return [
    '// Generated by @drinkit/security-starter: a page below declares no literal `auth` in its definePageMeta',
    'type DeclaresAuthInDefinePageMeta<Page extends never> = Page;',
    `export type PagesWithoutAuth = [\n${lines.join('\n')}\n];`,
    '',
  ].join('\n');
}
